-- 2. Создать многотабличную базу данных, заполнить ее данными, проверить содержимое ее таблиц.
-- Cоздание многотабличной базы данных:

--Арендаторы:
CREATE TABLE Tenants (
CustomerID INT PRIMARY KEY, -- Уникальный идентификатор арендатора, первичный ключ
CustomerType BIT NOT NULL, -- Тип арендатора: 0 - физическое лицо, 1 - юридическое лицо 
CustomerFio NVARCHAR(60), -- ФИО арендатора, заполняется только для физических лиц
CustomerName NVARCHAR(60), -- Название организации, заполняется только для юридических лиц
CustomerInn NVARCHAR(13), -- ИНН организации, 13 знаков для юридических лиц
Chief NVARCHAR(40), -- ФИО руководителя организации для юридических лиц
Phone NVARCHAR(12) NOT NULL, -- Контактный телефон арендатора, обязательное поле
Address NVARCHAR(60), -- Юридический адрес арендатора
Bank NVARCHAR(60), -- Название банка, обслуживающего организацию
District NVARCHAR(15), -- Район города, в котором находится арендатор
Worker NVARCHAR(30), -- Ответственное лицо от арендатора для связи
PhoneWorker NVARCHAR(12) -- Телефон ответственного лица
);
GO

-- Помещение:
CREATE TABLE Premises (
HallID INT PRIMARY KEY, -- Уникальный номер помещения, первичный ключ
Square INT NOT NULL, -- Площадь помещения в квадратных метрах, обязательное поле
Size NVARCHAR(20), -- Размеры помещения в формате "ширина x длина"
Floor INT, -- Номер этажа, на котором расположено помещение
PhoneHall BIT DEFAULT 0, -- Наличие телефона в помещении: 0 - нет, 1 - есть, по умолчанию 0
Decoration NVARCHAR(10) -- Тип отделки помещения: обычная, улучшенная, евро
);
GO

-- Договоры аренды:
CREATE TABLE Contracts (
TreatyID INT PRIMARY KEY, -- Уникальный номер договора аренды, первичный ключ
CustomerID INT NOT NULL, -- Внешний ключ, ссылается на арендатора из таблицы Tenants
HallID INT NOT NULL, -- Внешний ключ, ссылается на помещение из таблицы Premises
Type BIT DEFAULT 1, -- Статус договора: 1 - действует, 0 - закрыт, по умолчанию 1
DateStart DATE NOT NULL, -- Дата начала действия договора, обязательное поле
DateStop DATE, -- Дата окончания действия договора
Period NVARCHAR(20), -- Периодичность оплаты: ежемесячно, ежеквартально
Value MONEY NOT NULL, -- Сумма арендной платы в рублях, обязательное поле
Inspector NVARCHAR(30), -- Ответственное лицо от арендодателя
Target NVARCHAR(30), -- Цель использования помещения: офис, магазин, склад
Tax MONEY DEFAULT 0, -- Штраф за нарушение условий договора, по умолчанию 0
FOREIGN KEY (CustomerID) REFERENCES Tenants(CustomerID), -- Обеспечивает целостность ссылки на арендатора
FOREIGN KEY (HallID) REFERENCES Premises(HallID) -- Обеспечивает целостность ссылки на помещение
);
GO


