-- КРИТЕРИЙ 5: Удаление помещений на 1-м этаже
-- 8. Удаление договоров для помещений на 1-м этаже
DELETE FROM Contracts
WHERE HallID IN (SELECT HallID FROM Premises WHERE Floor = 1);
GO
-- 9. Удаление помещений на 1-м этаже
DELETE FROM Premises
WHERE Floor = 1;
GO

-- КРИТЕРИЙ 6: Удаление неиспользуемых помещений (без договоров)
-- 10. Удаление помещений, на которые нет договоров
DELETE FROM Premises
WHERE HallID NOT IN (SELECT DISTINCT HallID FROM Contracts);
GO


-- ПРОВЕРКА РЕЗУЛЬТАТОВ УДАЛЕНИЯ
SELECT 'Tenants (арендаторы)' AS TableName, COUNT(*) AS RemainingRows FROM
Tenants
UNION ALL
SELECT 'Premises (помещения)', COUNT(*) FROM Premises
UNION ALL
SELECT 'Contracts (договоры)', COUNT(*) FROM Contracts;
GO

