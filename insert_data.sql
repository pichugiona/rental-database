  MAX(p.Square) AS МаксимальнаяПлощадьПомещения
FROM Contracts c
INNER JOIN Premises p ON c.HallID = p.HallID
WHERE c.Type = 1
GROUP BY p.Floor
ORDER BY p.Floor;
