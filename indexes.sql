  t.CustomerID,
  ISNULL(t.CustomerFio, t.CustomerName) AS Арендатор,
  p.HallID,
  p.Square
FROM Tenants t
CROSS JOIN Premises p;
GO
-- LEFT OUTER JOIN (все арендаторы, даже без договоров)
SELECT
  t.CustomerID,
  ISNULL(t.CustomerFio, t.CustomerName) AS Арендатор,
  c.TreatyID,
  c.Value
FROM Tenants t
LEFT JOIN Contracts c ON t.CustomerID = c.CustomerID;
GO
-- RIGHT OUTER JOIN (все помещения, даже без договоров)
SELECT
  p.HallID,
  p.Square,
  c.TreatyID,
  c.Value
FROM Contracts c
RIGHT JOIN Premises p ON c.HallID = p.HallID;
GO
-- FULL OUTER JOIN (все арендаторы и все договоры)
SELECT
  t.CustomerID,
  ISNULL(t.CustomerFio, t.CustomerName) AS Арендатор,
  c.TreatyID,
  c.Value
FROM Tenants t
FULL OUTER JOIN Contracts c ON t.CustomerID = c.CustomerID;
GO


